  Map<String, dynamic> currentStudent,
  Map<String, int> targets,
) {
  bool same(Map<String, dynamic> a, Map<String, dynamic> b) =>
      a.length == b.length &&
      a.keys.every((key) => b.containsKey(key) && a[key] == b[key]);
  return same(
        currentStudent,
        mockStudentCalculationSampleInput["current_student"]
            as Map<String, dynamic>,
      ) &&
      same(
        targets,
        mockStudentCalculationSampleInput["targets"] as Map<String, dynamic>,
      );
}

