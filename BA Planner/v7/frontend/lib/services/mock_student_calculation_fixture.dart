// MC1: goal-aware Mock calculation for the Windows mock app (development and review only).
// The canned [mockStudentCalculationWire] above stays the answer for the shared fixture input
// ([mockStudentCalculationSampleInput]) and for `MockAppService()` without a full catalog.
// The rule table below is a plausible shape, NOT real game values, and not a port of
// backend/core/planning_calc.py. Every step is target minus current (never negative):
//
// | target key           | credits per step (breakdown) | resource per step                                   |
// |----------------------|------------------------------|-----------------------------------------------------|
// | level                | 6,825 (level)                | activity report x2, grade by the new level:         |
// |                      |                              |   <=40 Item_Icon_ExpItem_1, <=70 _2, else _3        |
// | student_star         | 600,000 (student_star)       | Item_Icon_SecretStone_<id> x100                     |
// | weapon_star          | 500,000 (weapon_star)        | Item_Icon_SecretStone_<id> x70                      |
// | weapon_level         | 50,000 (weapon_level)        | Equipment_Icon_WeaponExpGrowthA_0 x1 (always A)     |
// | ex_skill             | 80,000 (ex_skill)            | Item_Icon_Material_ExSkill_<school>_<g> x12,        |
// |                      |                              |   g = new level - 2 (0..3)                          |
// | skill1/skill2/skill3 | 15,000 (skill)               | Item_Icon_SkillBook_<school>_<g> x7,                |
// |                      |                              |   g = (new level - 2) ~/ 2 (0..3)                   |
// | equip1..3_tier       | 5,000 (equipment)            | Equipment_Icon_<slot>_Tier<t> x15, t = new tier     |
// | equip1..3_level      | 100 (equipment)              | Equipment_Icon_Exp_0 x1                             |
// | equip4_tier          | 250,000 (favorite_item)      | Item_Icon_Favor_Selection x2                        |
