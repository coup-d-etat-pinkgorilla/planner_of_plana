/// MC1 goal-aware wire (owned/shortage null; the caller applies holdings). [displayName],
/// [school] and [equipmentSlots] come from the student catalog and may be unknown (null).
Map<String, dynamic> mockGoalAwareStudentCalculationWire({
  required Map<String, dynamic> currentStudent,
  required Map<String, int> targets,
  String? displayName,
  String? school,
  List<String?> equipmentSlots = const [null, null, null],
}) {
  final breakdown = {for (final key in _mockCreditCategories) key: 0};
  final rows = <String, Map<String, dynamic>>{};
  void add(String? key, String name, String category, int amount) {
    if (key == null) return;
    final row = rows.putIfAbsent(
      key,
      () => {
        "resource_key": key,
        "item_id": key,
        "display_name": name,
        "category": category,
        "required": 0,
        "owned": null,
        "shortage": null,
        "affected_stage_ids": ["growth-calculator-stage"],
      },
    );
    row["required"] = (row["required"] as int) + amount;
  }

  // Current value, or null when it is not known (missing key / null / not a number).
  int? current(String key) {
    if (key.endsWith("_tier")) {
      final field = key.substring(0, key.length - "_tier".length);
      if (!currentStudent.containsKey(field)) return null;
      final raw = currentStudent[field];
      if (raw == null) return 0;
      final match = RegExp(r"^T(\d+)$").firstMatch(raw.toString());
      return match == null ? null : int.parse(match.group(1)!);
    }
    final raw = currentStudent[key];
    return raw is int ? raw : null;
  }

  // One price per step from current to target; [price] gets the value after the step.
  void steps(
    String key,
    String category,
    int credits,
    void Function(int value) price,
  ) {
    final from = current(key);
    final to = targets[key];
    if (from == null || to == null) return;
    for (var value = from + 1; value <= to; value++) {
      breakdown[category] = breakdown[category]! + credits;
      price(value);
    }
  }

  final studentId = currentStudent["student_id"] as String?;
  final eleph = studentId == null ? null : "Item_Icon_SecretStone_$studentId";
  final elephName = "${displayName ?? studentId}의 엘레프";
  final compactSchool = school?.replaceAll(" ", "").toLowerCase();
  final schoolKey = _mockCalculationSchools
      .where((known) => known.toLowerCase() == compactSchool)
      .firstOrNull;

  steps("level", "level", 6825, (value) {
    final grade = value <= 40 ? 1 : (value <= 70 ? 2 : 3);
    add(
      "Item_Icon_ExpItem_$grade",
      _mockActivityReportNames[grade],
      "activity_report",
      2,
    );
  });
  steps("student_star", "student_star", 600000, (_) {
    add(eleph, elephName, "student_eleph", 100);
  });
  steps("weapon_star", "weapon_star", 500000, (_) {
    add(eleph, elephName, "student_eleph", 70);
  });
  steps("weapon_level", "weapon_level", 50000, (_) {
    add("Equipment_Icon_WeaponExpGrowthA_0", "스프링 T1", "equipment", 1);
  });
  steps("ex_skill", "ex_skill", 80000, (value) {
    final grade = (value - 2).clamp(0, 3);
    add(
      schoolKey == null
          ? null
          : "Item_Icon_Material_ExSkill_${schoolKey}_$grade",
      "$schoolKey BD T${grade + 1}",
      "tactical_bd",
      12,
    );
  });
  for (final skill in const ["skill1", "skill2", "skill3"]) {
    steps(skill, "skill", 15000, (value) {
      final grade = ((value - 2) ~/ 2).clamp(0, 3);
      add(
        schoolKey == null ? null : "Item_Icon_SkillBook_${schoolKey}_$grade",
        "$schoolKey Note T${grade + 1}",
        "tech_notes",
        7,
      );
    });
  }
  for (var slot = 0; slot < 3; slot++) {
    final name = slot < equipmentSlots.length ? equipmentSlots[slot] : null;
    steps("equip${slot + 1}_tier", "equipment", 5000, (value) {
      add(
        name == null ? null : "Equipment_Icon_${name}_Tier$value",
        "$name T$value",
        "equipment",
        15,
      );
    });
    steps("equip${slot + 1}_level", "equipment", 100, (_) {
      add("Equipment_Icon_Exp_0", "하급 강화석", "equipment", 1);
    });
  }
  steps("equip4_tier", "favorite_item", 250000, (_) {
    add("Item_Icon_Favor_Selection", "Item_Icon_Favor_Selection", "present", 2);
  });
  for (final entry in _mockWorkbooks.entries) {
    steps(entry.key, "potential", 100000, (_) {
      add(entry.value.$1, entry.value.$2, "workbook", 2);
    });
  }

  final credits = breakdown.values.fold<int>(0, (sum, amount) => sum + amount);
  return {
    "totals": {"credits": credits},
    "credit_breakdown": breakdown,
    "resources": [
      if (credits > 0)
        {
          "resource_key": "credits",
          "item_id": null,
          "display_name": "크레딧",
          "category": "credits",
          "required": credits,
          "owned": null,
          "shortage": null,
          "affected_stage_ids": ["growth-calculator-stage"],
        },
      ...rows.values,
    ],
    "warnings": <String>[],
  };
}
